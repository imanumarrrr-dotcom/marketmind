import re
from datetime import datetime
NUM = re.compile(r"\d[\d,]*\.?\d*")
STOP = set("the and for with that this from are was has have its their will per more than into about which what".split())
def nums(t): return {n.replace(",", "").rstrip(".") for n in NUM.findall(t or "")}
def words(t): return {w for w in re.findall(r"[a-z]{4,}", (t or "").lower()) if w not in STOP}
def overlap(a, b): wa = words(a); return len(wa & words(b)) / max(1, len(wa))
def age(date):
    try:
        y, m = int(date[:4]), int(date[5:7]); n = datetime.now(); return (n.year - y) + (n.month - m) / 12
    except Exception: return None
def recency(date):
    a = age(date); return "unknown" if a is None else "<=1y" if a <= 1 else "1-3y" if a <= 3 else ">3y"

LV = {"high": 3, "medium": 2, "low": 1, "unknown": 1}; NAME = {3: "high", 2: "medium", 1: "low"}

def assess(st, docs, rec):
    """Evidence Analyst. Thresholds: fact needs every number in the cited text and >=30% term overlap;
    low/unknown credibility, flagged documents and conflicts are stored but flagged with confidence=low."""
    res = st.results[rec["source_ref"]]; texts = res.get("texts", {})
    best, bo = max(((d, overlap(rec["claim"], t)) for d, t in texts.items()), key=lambda x: x[1], default=(None, 0))
    src = " ".join(texts.values()).replace(",", "")
    out = dict(decision="accept", doc=best, corroboration=[], conflicts=[], notes=[])
    if rec["claim_type"] == "fact":
        miss = [n for n in nums(rec["claim"]) if n not in src]
        if miss: return {**out, "decision": "reject", "notes": f"numbers {miss} not found in cited source {rec['source_ref']}"}
        if bo < 0.3: return {**out, "decision": "reject", "notes": f"claim shares only {bo:.0%} of its terms with the cited source"}
    doc = docs.get(best) if best else None
    cred = "high" if res["kind"] == "calculation" else (doc["credibility"] if doc else "unknown")
    out.update(cred=cred, recency=recency(doc["date"]) if doc else "unknown")
    cap = LV[cred]
    if rec.get("entity") and rec.get("attribute") and rec["claim_type"] == "fact":
        for e in st.evidence.values():
            if e["claim_type"] == "fact" and e.get("entity", "").lower() == rec["entity"].lower() \
               and e.get("attribute") == rec["attribute"] and e.get("doc_id") != best:
                (out["corroboration"] if nums(e["claim"]) == nums(rec["claim"]) else out["conflicts"]).append(e["evidence_id"])
    if not out["corroboration"] and cred != "high": cap = min(cap, 2)
    if cred in ("low", "unknown"): out["decision"] = "flag"; out["notes"].append("low credibility: attribute to source, do not state as established")
    if best in st.flags_docs(): out["decision"] = "flag"; cap = 1; out["notes"].append("source contains instruction-like text (flagged)")
    if out["conflicts"]: out["decision"] = "flag"; cap = 1; out["notes"].append(f"conflicts with {out['conflicts']}")
    out["conf"] = NAME[min(cap, {"high": 3, "medium": 2, "low": 1}[rec["confidence"]])]
    out["notes"] = "; ".join(out["notes"]) or "supported by cited source"
    return out

def add_uncertainty(st, qid, claim, source_ref="SYSTEM", links=(), notes="system-detected"):
    eid = f"E-{len(st.evidence) + 1:03d}"
    st.evidence[eid] = dict(evidence_id=eid, question_id=qid, claim=claim, claim_type="uncertainty", source_ref=source_ref,
                            source_kind="system_detected", source_detail="generated by code, not by a model", credibility="unknown",
                            recency="unknown", corroboration=list(links), confidence="high", analyst_notes=notes, entity="", attribute="", doc_id=None)
    st.add_log("evidence", f"{eid} uncertainty: {claim[:90]}"); return eid
